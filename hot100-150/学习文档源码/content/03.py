        # 辅助函数统计“至多 limit 种”，这类窗口的所有后缀也都合法。
        def at_most(limit: int) -> int:
            if limit <= 0:
                return 0
            # 记录当前窗口各值次数，删掉零次数键才能准确统计种类。
            freq: dict[int, int] = {}
            left = 0
            count = 0
            for right, x in enumerate(nums):
                freq[x] = freq.get(x, 0) + 1
                # 超出种类限制时移出左端，直到重新合法。
                while len(freq) > limit:
                    old = nums[left]
                    freq[old] -= 1
                    if freq[old] == 0:
                        del freq[old]
                    left += 1
                # 按右端点一次统计所有合法起点，不逐个枚举子数组。
                count += right - left + 1
            return count

        # 恰好 k 种 = 至多 k 种 - 至多 k-1 种，两次线性扫描。
